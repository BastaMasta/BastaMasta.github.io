/* Friendly aliases so calling code reads clearly. */
export const ICON = {
  UP: '\x01', DOWN: '\x02', LEFT: '\x03', RIGHT: '\x04',
  HEART: '\x05', BULLET: '\x06', BLOCK: '\x07', CART: '\x08',
};

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const CELL_W = 6;   // glyph + 1px letterspacing
export const CELL_H = 8;   // glyph + 1px leading

/* Compile the string table into bitmasks: one byte per row, bit 4 = leftmost. */
const compiled = new Map();
for (const [ch, spec] of Object.entries(G)) {
  const rows = spec.split(' ').filter(Boolean);
  const mask = new Uint8Array(GLYPH_H);
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y] || '.....';
    let bits = 0;
    for (let x = 0; x < GLYPH_W; x++) {
      if (row[x] === '#') bits |= 1 << (GLYPH_W - 1 - x);
    }
    mask[y] = bits;
  }
  compiled.set(ch, mask);
}

const FALLBACK = compiled.get('?');

export function glyph(ch) {
  return compiled.get(ch) || compiled.get(ch.toUpperCase()) || FALLBACK;
}

/* Sanity check used by the headless test harness. */
export function glyphCount() { return compiled.size; }
